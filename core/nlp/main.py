import spacy

nlp = spacy.load("ru_core_news_md")

TARGET_LEMMAS = {
    # базовое
    "сказка",

    # общеупотребимые
    "история",
    "рассказ",
    "повесть",

    # детское / разговорное
    "байка",
    "сказочка",

    # аудиоформаты
    "аудиосказка",
    "аудиоистория",

    # обобщённые формулировки
    "произведение",

    # === ДОБАВЛЕННЫЕ СИНОНИМЫ ===
    # базовые и литературные
    "притча",
    "легенда",
    "миф",
    "басня",
    "фэнтези",
    "фантастика",

    # общеупотребимые нарративные
    "новелла",
    "повествование",
    "нарратив",
    "сюжет",

    # устные, детские и разговорные
    "небылица",
    "небывальщина",
    "выдумка",
    "фантазия",
    "сказ",
    "побасенка",
    "басенка",

    # аудиоформаты и медиа
    "аудиокнига",
    "подкаст",
    "радиопостановка",
    "радиоспектакль",
    "озвучка",

    # фольклор и этнические
    "былина",
    "сказание",
    "быль",
    "предание",
    "эпос",
    "сага",
    "сказ-легенда",

    # обобщённые
    "текст",
    "литература",
    "чтение",
    "книга",
    "сборник",
    "цикл",
    "творчество",

    # тематические
    "страшилка",
    "смешинка",
    "колыбельная",
    "интерактивная_история",
    "диалоговый_рассказ",
}


def extract_fairy_tale(text: str) -> str | None:
    doc = nlp(text.lower())

    for i, token in enumerate(doc):
        if token.lemma_ in TARGET_LEMMAS:
            # берём всё ПОСЛЕ слова "сказка"
            tail = doc[i + 1:]

            result = " ".join(
                t.text for t in tail
                if not t.is_punct
            ).strip()

            return result if result else None

    return None


tests = [
    "включи сказку колобок",
    "поставь сказку про волка и семерых козлят",
    "давай страшную сказку про ведьм",
    "запусти пожалуйста сказку про красную шапочку",

]

for t in tests:
    print(t, "→", extract_fairy_tale(t))
