# =========================
# ОБЩИЙ ТЕСТЕР
# =========================
def test_samples(samples, expected_label):
    for text in samples:
        doc = nlp(text)

        score_story = doc.cats.get("включить_сказку", 0.0)
        score_weather = doc.cats.get("узнать_погоду", 0.0)
        score_other = doc.cats.get("другой_интент", 0.0)

        scores = {
            "включить_сказку": score_story,
            "узнать_погоду": score_weather,
            "другой_интент": score_other,
        }

        predicted = max(scores, key=scores.get)
        ok = "OK" if predicted == expected_label else "FAIL"

        print(f"[{ok}] {text}")
        print(
            f"  сказка:  {score_story:.2%} | "
            f"погода: {score_weather:.2%} | "
            f"другой: {score_other:.2%}"
        )
        print("-" * 70)


print("\n" + "=" * 20 + " STORY POSITIVE " + "=" * 20)
test_samples(positive_story_samples, "включить_сказку")

print("\n" + "=" * 20 + " WEATHER POSITIVE " + "=" * 20)
test_samples(positive_weather_samples, "узнать_погоду")

print("\n" + "=" * 20 + " WEATHER NEGATIVE " + "=" * 20)
test_samples(negative_weather_samples, "другой_интент")
